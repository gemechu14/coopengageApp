List<MccOption> searchMccOptions(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return merchantMccOptions;
  return merchantMccOptions.where((m) {
    return m.code.contains(q) || m.description.toLowerCase().contains(q);
  }).toList();
}
